import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const root=new URL('.',import.meta.url).pathname;
const read=f=>fs.readFileSync(root+f,'utf8');
for(const f of ['app.js','mastery.js','data-tools.js','pwa.js','service-worker.js'])execFileSync('node',['--check','--input-type=commonjs'],{input:read(f),stdio:['pipe','ignore','pipe']});
for(const f of ['index.html','app.css','app.js','mastery.js','data-tools.js','pwa.js','manifest.webmanifest','service-worker.js','icon.svg','icon-192.png','icon-512.png'])assert.ok(fs.existsSync(root+f),`missing ${f}`);
const html=read('index.html'),sw=read('service-worker.js'),manifest=JSON.parse(read('manifest.webmanifest')),app=read('app.js'),tools=read('data-tools.js'),pwa=read('pwa.js');
assert.ok(html.includes('href="app.css"')&&html.includes('src="mastery.js"'));
assert.ok(!/(^|["'])((css|js|assets))\//.test(html),'HTML contains nested runtime paths');
assert.ok(sw.includes('math-genius-v3.2-flat-shell-1')&&sw.includes("'./mastery.js'"));
assert.ok(!/(^|["'])((css|js|assets))\//.test(sw),'service worker contains nested runtime paths');
assert.equal(manifest.display,'standalone');
for(const icon of manifest.icons)assert.ok(fs.existsSync(root+icon.src),`missing manifest icon ${icon.src}`);
assert.ok(tools.includes('id=\"mg-install-settings\"'),'persistent install action missing from Settings');
assert.ok(tools.includes('id=\"mg-install\"'),'fixed install action missing');
assert.ok(pwa.includes('beforeinstallprompt')&&pwa.includes('appinstalled')&&pwa.includes('display-mode: standalone'),'PWA install lifecycle missing');
assert.ok(app.includes('dailyLearning:{},errorLog:[]'),'additive daily/error fields missing from fresh data');
assert.ok(app.includes('d.dailyLearning=d.dailyLearning&&typeof d.dailyLearning'), 'daily activity normalization missing');
assert.ok(app.includes('function showTutor('),'step-by-step tutor missing');
assert.ok(app.includes('x.les[0][1]!==x.les[0][0]'),'Smart Tutor should include available Vietnamese lesson guidance');
assert.ok(app.includes('function recordErrorReflection('),'error reflection missing');
assert.ok(app.includes('function parentPage('),'parent report missing');
assert.ok(app.includes('data-parent-topic'),'parent report practice actions missing');
assert.ok(app.includes('errorLog'),'error log persistence missing');
assert.ok(app.includes('supportNeeds>=2'),'repeated learner reflections should lower Smart Mode difficulty by one level');
assert.ok(!app.includes('if(!ok&&!Q.errorRecorded)recordErrorReflection(q,\'unsure\')'),'skipping reflection must not be recorded as a learner self-report');
assert.ok(app.includes('Q.fin=0;Q.errorRecorded=false'),'error reflection state should reset for each question');
const context={window:{},Date,Math,console};vm.createContext(context);vm.runInContext(read('mastery.js'),context);const M=context.window.MGMastery;
assert.ok(M&&typeof M.record==='function'&&typeof M.assess==='function');
const learner={tp:{legacy:{c:2,t:3}},mistakes:[{tid:'legacy'}],sessions:[{id:'old'}]};
M.record(learner,{tid:'demo'},true,0,1);M.record(learner,{tid:'demo'},false,1,1);
assert.equal(M.assess(learner,'demo').attempts,2);
const dayKey=new Date(Date.now()-new Date().getTimezoneOffset()*60000).toISOString().slice(0,10);
assert.equal(learner.dailyLearning[dayKey].answered,2);assert.equal(learner.tp.legacy.c,2);assert.equal(learner.mistakes.length,1);assert.equal(learner.sessions.length,1);
console.log('Math Genius V3.2 flat smoke tests passed.');
